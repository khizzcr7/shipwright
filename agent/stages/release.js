// RELEASE stage - drafts release notes and proposes the state-changing
// actions (write the notes file, bump the version). Under Shipwright's
// Assisted autonomy level the agent proposes; a human approves. Nothing here
// mutates the project until applyProposal is called by the orchestrator
// after approval.
import { execFile } from 'node:child_process';
import { readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { readText, result } from './util.js';

function readPkg(ctx) {
  return JSON.parse(readFileSync(join(ctx.root, 'package.json'), 'utf8'));
}

export function nextPatch(version) {
  const parts = String(version).split('.').map((n) => Number(n) || 0);
  parts[2] = (parts[2] || 0) + 1;
  return parts.slice(0, 3).join('.');
}

async function gitLog(ctx) {
  return new Promise((resolve) => {
    execFile('git', ['-C', ctx.root, 'log', '--oneline', '-5'], (err, stdout) => {
      if (err) resolve(null);
      else resolve(stdout.trim().split('\n').filter(Boolean));
    });
  });
}

export async function buildReleaseNotes(ctx) {
  const pkg = readPkg(ctx);
  const commits = await gitLog(ctx);
  const lines = [
    `# Release notes - ${pkg.name} v${pkg.version}`,
    '',
    `Generated by the Shipwright delivery agent on ${new Date().toISOString()}.`,
    '',
  ];
  if (commits && commits.length) {
    lines.push('## Recent commits', ...commits.map((c) => `- ${c}`), '');
  } else {
    lines.push('## Highlights', '- Delivery pipeline verified end to end by the Shipwright stage engine.', '');
  }
  lines.push('## Delivery report', 'See reports/delivery-report.md for the full stage-by-stage readiness report.', '');
  return lines.join('\n');
}

export async function run(ctx) {
  const pkg = readPkg(ctx);
  const notes = await buildReleaseNotes(ctx);
  const proposals = [
    { id: 'release-notes', description: 'Write RELEASE_NOTES.md with the drafted notes' },
    { id: 'version-bump', description: `Bump package.json version ${pkg.version} -> ${nextPatch(pkg.version)}` },
  ];
  return {
    ...result('release', 'Release', 'pass',
      [`Release notes drafted for ${pkg.name} v${pkg.version} (${notes.split('\n').length} lines).`,
       'Two state-changing actions proposed for human approval (Assisted autonomy).']),
    proposals,
  };
}

export async function applyProposal(ctx, id) {
  if (id === 'release-notes') {
    writeFileSync(join(ctx.root, 'RELEASE_NOTES.md'), await buildReleaseNotes(ctx));
    return 'RELEASE_NOTES.md written.';
  }
  if (id === 'version-bump') {
    const pkg = readPkg(ctx);
    pkg.version = nextPatch(pkg.version);
    writeFileSync(join(ctx.root, 'package.json'), `${JSON.stringify(pkg, null, 2)}\n`);
    return `package.json version bumped to ${pkg.version}.`;
  }
  return `Unknown proposal: ${id}`;
}
